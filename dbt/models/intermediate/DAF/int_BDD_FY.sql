
WITH agg AS (
    
    SELECT
  MOIS,
  SUM(CASE WHEN TYPE = 'REALISE' AND CODE_RUBRIQUE = 'C110'
      AND ANNEE = CAST(EXTRACT(YEAR FROM CURRENT_DATE()) AS STRING)
      THEN VALEUR ELSE 0 END) AS ca_current_year,

  SUM(CASE WHEN TYPE = 'BUDGET' AND CODE_RUBRIQUE = 'C110'
      AND ANNEE = CAST(EXTRACT(YEAR FROM CURRENT_DATE())  AS STRING)
      THEN VALEUR ELSE 0 END) AS ca_BUDGET_current_year,

  SUM(CASE WHEN CODE_RUBRIQUE = 'C127' AND TYPE = 'REALISE' 
    AND ANNEE = CAST(EXTRACT(YEAR FROM CURRENT_DATE()) AS STRING) 
    THEN VALEUR ELSE 0 END) AS MB_ACTUAL_Current_Year,

  SUM(CASE WHEN CODE_RUBRIQUE = 'C127' AND TYPE = 'BUDGET' 
    AND ANNEE = CAST(EXTRACT(YEAR FROM CURRENT_DATE()) AS STRING) 
    THEN VALEUR ELSE 0 END) AS MB_BUDGET_Current_Year


FROM {{ref('int_BDD_BU')}}
WHERE ANNEE IN (
  CAST(EXTRACT(YEAR FROM CURRENT_DATE()) AS STRING)
)
GROUP BY MOIS 
ORDER BY MOIS

)

SELECT 
*,
SAFE_DIVIDE (MB_ACTUAL_Current_Year , ca_current_year) AS tx_MB_ACTUAL,
SAFE_DIVIDE (MB_BUDGET_Current_Year, ca_BUDGET_current_year) AS tx_MB_BUDGET
FROM agg