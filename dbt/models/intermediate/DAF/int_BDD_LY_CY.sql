
WITH agg AS (
    
    SELECT
  MOIS,
  SUM(CASE WHEN TYPE = 'REALISE' AND CODE_RUBRIQUE = 'C110'
      AND ANNEE = CAST(EXTRACT(YEAR FROM CURRENT_DATE()) AS STRING)
      THEN VALEUR ELSE 0 END) AS ca_n,

  SUM(CASE WHEN TYPE = 'REALISE' AND CODE_RUBRIQUE = 'C110'
      AND ANNEE = CAST(EXTRACT(YEAR FROM CURRENT_DATE()) - 1 AS STRING)
      THEN VALEUR ELSE 0 END) AS ca_n1,

  SUM(CASE WHEN CODE_RUBRIQUE = 'C127' AND TYPE = 'REALISE' 
    AND ANNEE = CAST(EXTRACT(YEAR FROM CURRENT_DATE()) AS STRING) 
    THEN VALEUR ELSE 0 END) AS MB_ACTUAL_Current_Year,

  SUM(CASE WHEN CODE_RUBRIQUE = 'C127' AND TYPE = 'REALISE' 
    AND ANNEE = CAST(EXTRACT(YEAR FROM CURRENT_DATE()) -1 AS STRING) 
    THEN VALEUR ELSE 0 END) AS MB_ACTUAL_LAST_Year


FROM {{ref('int_BDD_BU')}}
WHERE ANNEE IN (
  CAST(EXTRACT(YEAR FROM CURRENT_DATE()) AS STRING),
  CAST(EXTRACT(YEAR FROM CURRENT_DATE()) - 1 AS STRING)
)
GROUP BY MOIS 
ORDER BY MOIS

)

SELECT 
*,
SAFE_DIVIDE (MB_ACTUAL_Current_Year , ca_n) AS tx_MB_ACTUAL,
SAFE_DIVIDE (MB_ACTUAL_LAST_Year, ca_n1) AS tx_MB_LY
FROM agg